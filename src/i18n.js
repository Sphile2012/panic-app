const DICTS = { en, zu, xh, st, af };
export function registerStrings(strings) {
    for (const code of Object.keys(strings))
        Object.assign(DICTS[code], strings[code]);
}
let current = readLang();
function readLang() {
    try {
        const v = localStorage.getItem(LANG_KEY);
        if (v === 'en' || v === 'zu' || v === 'xh' || v === 'st' || v === 'af')
            return v;
    }
    catch { }
    return 'en';
}
export function getLang() {
    return current;
}
export function setLang(code) {
    current = code;
    try {
        localStorage.setItem(LANG_KEY, code);
    }
    catch { }
    document.documentElement.lang = code;
}
export function t(key, vars = {}) {
    let s = DICTS[current][key] ?? en[key] ?? key;
    for (const k of Object.keys(vars))
        s = s.split(`{${k}}`).join(String(vars[k]));
    return s;
}
export function authErrorKey(failure) {
    switch (failure) {
        case 'id': return 'auth.err.id';
        case 'invalid': return 'auth.err.invalid';
        case 'confirm': return 'auth.err.confirm';
        case 'service': return 'auth.err.service';
        default: return 'auth.err.generic';
    }
}
export function languageBarHtml() {
    return `
    <div class="lang-bar">
      <label class="auth-visually-hidden" for="language-select">${t('lang.title')}</label>
      <select class="lang-select" id="language-select" aria-label="${t('lang.title')}" data-language-select>
        ${LANGS.map(l => `<option value="${l.code}"${l.code === current ? ' selected' : ''}>${l.label}</option>`).join('')}
      </select>
    </div>
  `;
}
export function bindLanguageBar(root, rerender) {
    const select = root.querySelector('[data-language-select]');
    select?.addEventListener('change', () => {
        const selected = LANGS.find(language => language.code === select.value);
        if (!selected)
            return;
        setLang(selected.code);
        rerender();
    });
}
